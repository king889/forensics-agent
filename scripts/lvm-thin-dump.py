#!/usr/bin/env python3
"""lvm-thin-dump.py <镜像> --partition-lba N -o <输出目录> [--pv-offset 512]

从 E01/raw 镜像里把 LVM **thin pool** 拆出来，供 thin_ls / thin_dump 使用。

为什么要它：
    pve 的虚拟机磁盘放在 LVM thin pool 里。sleuthkit 读不了 LVM；
    dissect 能列出 LV 名字（pve-data_tdata / pve-data_tmeta）但拿不到物理偏移；
    `thin_ls` 需要「元数据设备」和「数据设备」两个**普通文件**。
    所以必须自己解析 LVM2 的文本元数据，把连续区间切出来。

做法：
    1. 读 PV 头，找到 LVM2 文本元数据区（以 "pve-data_tmeta {" 这类段落开头）
    2. 从 `extent_size` / `pe_start` 和每个 LV 的 `stripes = ["pv0", N]` 算出字节区间
    3. 把顶级 LV（tmeta / tdata / root 等）写成文件
    4. 打印建议的 thin_ls / thin_dump 命令

用法：
    lvm-thin-dump.py disk01.E01 --partition-lba 1050624 -o /tmp/lvm
    thin_ls /tmp/lvm/pve-data_tmeta
    thin_dump /tmp/lvm/pve-data_tmeta > /tmp/meta.xml
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


def open_image(path: str):
    if path.lower().endswith((".e01", ".ex01")):
        from dissect.evidence import ewf
        return ewf.EWF(path).open(), True
    return open(path, "rb"), False


def read_at(f, off: int, size: int) -> bytes:
    f.seek(off)
    return f.read(size)


def find_metadata_text(f, pv: int, span: int = 16 << 20) -> str:
    """取出含逻辑卷定义的元数据文本。

    坑：LVM 的 MDA 是环形写、多个副本，而且**副本边界和正文并不相邻**
    （有时 header 在尾、正文在前面）。按 "# Generated by LVM2" 切块会切出
    只有 VG 头、没有 logical_volumes 的碎片。
    所以直接定位 `logical_volumes {`，往前带一点上下文、往后取一段。
    """
    data = read_at(f, pv, span)
    i = data.find(b"logical_volumes")
    if i < 0:
        # 只拿到 VG 头的情况，退回给上层报错时能看到内容
        j = data.find(b"# Generated by LVM2")
        return data[max(0, j):j + 4000].decode("utf-8", "replace") if j >= 0 else ""

    start = max(0, i - 4096)
    chunk = data[start: i + (256 << 10)]
    z = chunk.find(b"\x00" * 32)
    if z > 0:
        chunk = chunk[:z]
    return chunk.decode("utf-8", "replace")


def parse_lvs(text: str) -> tuple[int, int, list[dict]]:
    """返回 (extent_size_bytes, pe_start_bytes, [ {name, start,int extents} ])"""
    m = re.search(r"extent_size\s*=\s*(\d+)", text)
    extent_size = int(m.group(1)) * 512 if m else 4 << 20
    m = re.search(r"pe_start\s*=\s*(\d+)", text)
    pe_start = int(m.group(1)) * 512 if m else 1 << 20

    lvs = []
    # 顶层段落：\n<name> {\n ... \n}
    for mm in re.finditer(r"^\s*([A-Za-z0-9_.\-]+)\s*\{\s*$", text, re.M):
        name = mm.group(1)
        if name in ("segment1", "segment2", "segment3", "pv0"):
            continue
        # 截取这一段（到下一个顶层 } 为止，粗略按 4000 字符）
        body = text[mm.end(): mm.end() + 4000]
        seg = re.search(
            r"segment1\s*\{[^}]*?start_extent\s*=\s*(\d+)[^}]*?"
            r"extent_count\s*=\s*(\d+)[^}]*?stripes\s*=\s*\[\s*\"pv\d+\"\s*,\s*(\d+)\s*\]",
            body, re.S)
        if seg:
            lvs.append({
                "name": name,
                "start": int(seg.group(1)),
                "extents": int(seg.group(2)),
                "pe": int(seg.group(3)),
            })
    return extent_size, pe_start, lvs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("--partition-lba", type=int, required=True, help="LVM 分区起始 LBA")
    ap.add_argument("-o", "--out", default="lvm-out")
    ap.add_argument("--only", help="只导出名字匹配该正则的 LV")
    ap.add_argument("--dry-run", action="store_true", help="只打印布局，不写文件")
    a = ap.parse_args()

    f, need_close = open_image(a.image)
    pv = a.partition_lba * 512
    text = find_metadata_text(f, pv)
    if not text:
        print("没找到 LVM2 元数据文本", file=sys.stderr)
        return 1

    extent_size, pe_start, lvs = parse_lvs(text)
    print(f"extent_size={extent_size/2**20:.1f}MiB  pe_start={pe_start}  "
          f"解析到 {len(lvs)} 个 LV", file=sys.stderr)
    if not lvs:
        print(text[:1500], file=sys.stderr)
        return 1

    # 多副本会重复解析出同名 LV，按名字去重（保留最后出现的，通常是最新的）
    dedup: dict[str, dict] = {}
    for lv in lvs:
        dedup[lv["name"]] = lv
    lvs = list(dedup.values())

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    only = re.compile(a.only) if a.only else None

    for lv in sorted(lvs, key=lambda x: -x["extents"]):
        name, n_ext = lv["name"], lv["extents"]
        if only and not only.search(name):
            continue
        off = pv + pe_start + lv["pe"] * extent_size
        size = n_ext * extent_size
        print(f"  {name:34} offset={off:>14}  size={size/2**30:7.2f} GiB  "
              f"({n_ext} extents)")
        if a.dry_run:
            continue
        dst = out / name
        f.seek(off)
        remain = size
        with dst.open("wb") as fh:
            while remain > 0:
                buf = f.read(min(8 << 20, remain))
                if not buf:
                    break
                fh.write(buf)
                remain -= len(buf)
        print(f"      → {dst}  ({dst.stat().st_size/2**30:.2f} GiB)")

    if need_close:
        try:
            f.close()
        except Exception:
            pass

    print("\n下一步：", file=sys.stderr)
    print(f"  thin_ls {out}/pve-data_tmeta                     # 列出 thin 卷", file=sys.stderr)
    print(f"  thin_dump {out}/pve-data_tmeta > {out}/meta.xml   # 完整映射", file=sys.stderr)
    print(f"  thin_ls -m  # 也可 --no-headers -o csv", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
